#!/usr/bin/env python3
"""Convert the FAA Releasable Aircraft database into compact JS files loadable from file://.
   Source: https://registry.faa.gov/database/ReleasableAircraft.zip (updated daily by FAA).
   Owner names/addresses from MASTER.txt are deliberately NOT included."""
import csv, json, os, sys, random, datetime
SRC=sys.argv[1] if len(sys.argv)>1 else '/tmp/faa'; OUT=sys.argv[2] if len(sys.argv)>2 else 'data'
os.makedirs(OUT,exist_ok=True)
def rows(name):
    with open(os.path.join(SRC,name),encoding='latin-1',newline='') as f:
        r=csv.reader(f); h=[x.replace('\xef\xbb\xbf','').replace('ï»¿','').strip() for x in next(r)]
        for row in r: yield {h[i]:(row[i].strip() if i<len(row) else '') for i in range(len(h))}
built=datetime.date.fromtimestamp(os.path.getmtime(os.path.join(SRC,'ACFTREF.txt'))).isoformat()
mfrs=[];mi={};lines=[]
for r in rows('ACFTREF.txt'):
    m=r['MFR']
    if m not in mi: mi[m]=len(mfrs); mfrs.append(m)
    w=r['AC-WEIGHT'].replace('CLASS','').strip()
    lines.append('|'.join([r['CODE'],str(mi[m]),r['MODEL'].replace('|','/'),r['TYPE-ACFT'],r['TYPE-ENG'],str(int(r['NO-ENG'] or 0)),str(int(r['NO-SEATS'] or 0)),w,r['BUILD-CERT-IND'],str(int(r['SPEED'] or 0))]))
eng=[]
for r in rows('ENGINE.txt'):
    eng.append('|'.join([r['CODE'],r['MFR'],r['MODEL'],r['TYPE'],str(int(r['HORSEPOWER'] or 0)),str(int(r['THRUST'] or 0))]))
with open(os.path.join(OUT,'faa-types.js'),'w') as f:
    f.write('/* FAA Aircraft Registry ACFTREF + ENGINE (public domain, registry.faa.gov). Built %s. */\n'%built)
    f.write('window.FAA_TYPES='+json.dumps({'built':built,'mfrs':mfrs,'rows':'\n'.join(lines),'engines':'\n'.join(eng)},separators=(',',':'))+';\n')
taken=set()
shards={}
for r in rows('MASTER.txt'):
    n=r['N-NUMBER'];taken.add(n)
    rec='|'.join([n,r['SERIAL NUMBER'].replace('|','/'),r['MFR MDL CODE'],r['ENG MFR MDL'],r['YEAR MFR'],r['STATUS CODE'],r['CERT ISSUE DATE'],r['AIR WORTH DATE'],r['EXPIRATION DATE'],r['TYPE REGISTRANT'],r['MODE S CODE HEX'].strip(),r['CERTIFICATION'].strip()])
    shards.setdefault(n[0],[]).append(rec)
for k,v in shards.items():
    with open(os.path.join(OUT,'faa-master-%s.js'%k),'w') as f:
        f.write('/* FAA MASTER.txt shard "%s" — owner names/addresses excluded. Built %s. */\n'%(k,built))
        f.write('(window.FAA_MASTER=window.FAA_MASTER||{})[%s]=%s;\n'%(json.dumps(k),json.dumps('\n'.join(v))))
for name in ('RESERVED.txt','DEREG.txt'):
    for r in rows(name): taken.add(r['N-NUMBER'])
random.seed(7);free=[]
for sfx in ['VK','VX','VQ','ZK']:
    for i in range(100,999):
        t='%d%s'%(i,sfx)
        if t not in taken: free.append('N'+t)
random.shuffle(free)
fixed=[t for t in ['N350VK','N612VK','N822VK'] if t[1:] not in taken]
with open(os.path.join(OUT,'demo-tails.js'),'w') as f:
    f.write('/* N-numbers verified NOT present in FAA MASTER, RESERVED or DEREG as of %s — safe for fictitious demo aircraft. */\n'%built)
    f.write('window.DEMO_TAILS='+json.dumps({'fixed':fixed,'pool':free[:80]})+';\n')
print('types',len(lines),'mfrs',len(mfrs),'engines',len(eng),'master',sum(len(v) for v in shards.values()),'fixed',fixed)
# ---- dataset version manifest (record keys: ACFTREF by CODE = MFR-MDL-SERIES code; MASTER by N-NUMBER + SERIAL NUMBER) ----
import hashlib
def sha(p):
    h=hashlib.sha256()
    with open(p,'rb') as f:
        for b in iter(lambda:f.read(1<<20),b''): h.update(b)
    return h.hexdigest()
zp=os.path.join(SRC,'ReleasableAircraft.zip')
man={'dataset':'FAA Aircraft Registration Releasable Database','source':'https://registry.faa.gov/database/ReleasableAircraft.zip',
     'layout':'https://registry.faa.gov/database/ardata.pdf','version':built,'built':datetime.datetime.utcnow().replace(microsecond=0).isoformat()+'Z',
     'zipSha256':sha(zp) if os.path.exists(zp) else None,
     'files':{n:{'sha256':sha(os.path.join(SRC,n)),'bytes':os.path.getsize(os.path.join(SRC,n))} for n in ['ACFTREF.txt','ENGINE.txt','MASTER.txt','DEREG.txt','RESERVED.txt'] if os.path.exists(os.path.join(SRC,n))},
     'counts':{'types':len(lines),'engines':len(eng),'registrations':sum(len(v) for v in shards.values())},
     'keys':{'ACFTREF':'CODE (MFR-MDL-SERIES code, 7 chars)','ENGINE':'CODE','MASTER':'N-NUMBER + SERIAL NUMBER'},
     'refresh':'FAA publishes the database daily (federal working days); production syncs nightly server-side'}
with open(os.path.join(OUT,'faa-version.js'),'w') as f:
    f.write('/* FAA dataset version manifest — generated by tools/build_faa.py */\nwindow.FAA_VERSION='+json.dumps(man,indent=1)+';\n')
print('manifest',man['version'],man['zipSha256'])
